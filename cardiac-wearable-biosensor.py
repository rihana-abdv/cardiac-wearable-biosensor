# computing features for each dataset, and adding synthetic data for blood oxygen and motion

def compute_features_from_rr(rr_seconds, window_size=60, step=30):
    features = []
    rr = np.array(rr_seconds, dtype=float)
    rr = rr[(rr > 0.25) & (rr < 2.5)]
    if len(rr) < window_size:
        return features
    for start in range(0, len(rr) - window_size, step):
        window   = rr[start:start + window_size]
        bpm_mean = 60.0 / np.mean(window)
        diff     = np.diff(window)
        rmssd    = np.sqrt(np.mean(diff**2)) * 1000
        sdnn     = np.std(window) * 1000
        features.append([bpm_mean, rmssd, sdnn])
    return features

def add_synthetic_cols(features, label,
                       spo2_mean, spo2_std,
                       motion_mean_range, motion_std_range):
    n   = len(features)
    arr = np.array(features)
    spo2     = np.clip(np.random.normal(spo2_mean, spo2_std, n), 90, 100)
    mot_mean = np.random.uniform(*motion_mean_range, n)
    mot_std  = np.random.uniform(*motion_std_range,  n)
    return pd.DataFrame({
        'bpm_mean':    arr[:, 0],
        'hrv_rmssd':   arr[:, 1],
        'hrv_sdnn':    arr[:, 2],
        'spo2':        spo2,
        'motion_mean': mot_mean,
        'motion_std':  mot_std,
        'label':       label
    })


