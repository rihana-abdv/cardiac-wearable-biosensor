# verify it works in Python first
def run_model_python(raw_features):
    # scale
    scaled = [(raw_features[i] - scaler_means[i]) / scaler_stds[i]
              for i in range(6)]
    x = np.array(scaled)

    # layer 0
    l0 = np.maximum(0, x @ w0 + b0)
    # layer 1
    l1 = np.maximum(0, l0 @ w1 + b1)
    # layer 2 + softmax
    l2 = l1 @ w2 + b2
    probs = np.exp(l2 - l2.max()) / np.exp(l2 - l2.max()).sum()
    return probs

