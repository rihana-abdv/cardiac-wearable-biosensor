def array_to_c(arr, name, dtype="float"):
    flat = arr.flatten()
    vals = ", ".join([f"{v:.6f}f" for v in flat])
    if arr.ndim == 2:
        rows, cols = arr.shape
        return f"const {dtype} {name}[{rows}][{cols}] = {{{vals}}};\n"
    else:
        size = len(flat)
        return f"const {dtype} {name}[{size}] = {{{vals}}};\n"

