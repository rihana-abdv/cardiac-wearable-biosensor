def upsample_with_noise(df_class, target_n):
    """
    Duplicates rows with tiny gaussian noise to reach target_n.
    Noise is small enough to stay physiologically valid.
    Only adds noise to numeric feature columns, not the label.
    """
    feature_cols = ['bpm_mean', 'hrv_rmssd', 'hrv_sdnn',
                    'spo2', 'motion_mean', 'motion_std']

    current = df_class.copy()
    needed  = target_n - len(current)

    # sample 'needed' rows randomly (with replacement) and add noise
    extras  = current.sample(n=needed, replace=True, random_state=42).copy()

    # noise scale is 1% of each feature's std — tiny perturbation
    for col in feature_cols:
        noise_scale = current[col].std() * 0.01
        extras[col] = extras[col] + np.random.normal(0, noise_scale, len(extras))

    # clip spo2 back to valid range after noise
    extras['spo2'] = extras['spo2'].clip(85, 100)

    upsampled = pd.concat([current, extras], ignore_index=True)
    return upsampled


